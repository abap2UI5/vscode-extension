/*
 * Only the identity fields are decided here. The dependency versions and the
 * script bodies come from app-template's own package.json, because a hand-kept
 * second copy of "which linter version does a new project get" is exactly the
 * thing that was wrong: this file shipped ^0.1.1 for two releases of 0.2.x.
 */
const PACKAGE_JSON = (projectName: string): string => {
  const template = JSON.parse(TEMPLATE_FILES["package.json"]) as {
    scripts: Record<string, string>;
    devDependencies: Record<string, string>;
    engines?: Record<string, string>;
    /** app-template carries an `overrides` block while the published linter's
     *  peer range is narrower than the render-runtime it is released beside -
     *  without it `npm ci` refuses the very pairing the template documents.
     *  Copied rather than judged: it is a fact about the registry, and the
     *  template is where it is decided and where it will be removed. */
    overrides?: Record<string, unknown>;
  };
  const scripts: Record<string, string> = {};
  for (const [name, body] of Object.entries(template.scripts)) {
    // The template's `rename` and `check:pin` run files out of its `scripts/`
    // directory, which this scaffold does not write - a script that cannot run
    // is worse than one that is not offered.
    if (!body.includes("scripts/")) {
      scripts[name] = body;
    }
  }
  return `${JSON.stringify(
    {
      name: projectName,
      private: true,
      version: "1.0.0",
      description: "abap2UI5 app",
      scripts,
      devDependencies: template.devDependencies,
      engines: template.engines ?? { node: ">=22" },
      ...(template.overrides ? { overrides: template.overrides } : {}),
    },
    null,
    2
  )}\n`;
};

/**
 * Every file a new abap2UI5 project needs, as data.
 *
 * @param projectName  repository/npm name, e.g. `my-app`
 * @param className    the app class, lower case, e.g. `zcl_my_app`
 */
export function scaffoldFiles(
  projectName: string,
  className: string,
  template: AppTemplate
): ScaffoldFile[] {
  const cls = className.toLowerCase();
  return [
    { path: `src/${cls}.clas.abap`, content: `${templateSource(template, cls)}\n` },
    { path: `src/${cls}.clas.xml`, content: sidecar(cls), bom: true },
    {
      path: "src/package.devc.xml",
      bom: true,
      content: `<?xml version="1.0" encoding="utf-8"?>
<abapGit version="v1.0.0" serializer="LCL_OBJECT_DEVC" serializer_version="v1.0.0">
 <asx:abap xmlns:asx="http://www.sap.com/abapxml" version="1.0">
  <asx:values>
   <DEVC>
    <CTEXT>${projectName}</CTEXT>
   </DEVC>
  </asx:values>
 </asx:abap>
</abapGit>
`,
    },
    {
      path: ".abapgit.xml",
      bom: true,
      content: `<?xml version="1.0" encoding="utf-8"?>
<asx:abap xmlns:asx="http://www.sap.com/abapxml" version="1.0">
 <asx:values>
  <DATA>
   <NAME>${projectName}</NAME>
   <MASTER_LANGUAGE>E</MASTER_LANGUAGE>
   <STARTING_FOLDER>/src/</STARTING_FOLDER>
   <FOLDER_LOGIC>PREFIX</FOLDER_LOGIC>
  </DATA>
 </asx:values>
</asx:abap>
`,
    },
    // Verbatim from app-template - see the header. These are the files that
    // decide what a project is checked by, and there is one source for them:
    // app-template's template.json says which they are, so a file added over
    // there is handed out here without anybody editing this list.
    ...VERBATIM_FILES.map((path) => ({ path, content: TEMPLATE_FILES[path] })),

    { path: "package.json", content: PACKAGE_JSON(projectName) },
    { path: ".github/workflows/check.yml", content: CHECK_WORKFLOW() },
    { path: "AGENTS.md", content: AGENTS(projectName, cls) },
    { path: "README.md", content: README(projectName, cls) },
  ];
}

/** Built rather than written literally: an invisible character in a source
 *  file is the kind of thing an editor, a formatter or a paste drops without
 *  anyone noticing. */
const BOM = String.fromCharCode(0xfeff);

/**
 * The exact text to write for one scaffold file - the BOM belongs to the
 * content, so that whether a file gets one is decided (and tested) here
 * rather than at the call site.
 */
export function scaffoldText(file: ScaffoldFile): string {
  return file.bom ? BOM + file.content : file.content;
}

/** npm package names: lower case, no spaces, no leading dot or underscore. */
export function projectNameFrom(folderName: string): string {
  const name = folderName
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^[._-]+/, "")
    .replace(/-+$/, "");
  return name || "abap2ui5-app";
}

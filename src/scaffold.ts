/**
 * Every file a new abap2UI5 project needs, as data.
 *
 * @param projectName  repository/npm name, e.g. `my-app`
 * @param className    the app class, lower case, e.g. `zcl_my_app`
 * @param packageText  the ABAP package description abapGit shows; the
 *                     project name when not given
 */
export function scaffoldFiles(
  projectName: string,
  className: string,
  packageText: string = projectName
): ScaffoldFile[] {
  const cls = className.toLowerCase();
  const fromTemplate = templateProjectFiles(projectName, cls, packageText);
  return [
    // app-template's own files, as its template.json lists them and with the
    // substitutions it names - see the header. One source decides what a
    // project is checked by and briefed with, so a file added over there is
    // handed out here without anybody editing a list.
    ...fromTemplate,
    // The project's own README - unless the template ever starts handing one
    // out, in which case that one is the project's.
    ...(fromTemplate.some((f) => f.path === "README.md")
      ? []
      : [{ path: "README.md", content: README(projectName, cls) }]),
  ];
}

/** Built rather than written literally: an invisible character in a source
 *  file is the kind of thing an editor, a formatter or a paste drops without
 *  anyone noticing. */
const BOM = String.fromCharCode(0xfeff);

/**
 * The exact text to write for one scaffold file - the BOM belongs to the
 * content, so that whether a file gets one is decided (and tested) here
 * rather than at the call site.
 */
export function scaffoldText(file: ScaffoldFile): string {
  return file.bom ? BOM + file.content : file.content;
}

/** npm's ceiling on a package name (validate-npm-package-name). */
export const NPM_NAME_MAX = 214;

/** The two names npm refuses outright, whatever their characters. */
const NPM_BLOCKED_NAMES = new Set(["node_modules", "favicon.ico"]);

/**
 * The npm rules the character filter alone does not enforce, applied to a
 * name already made of `[a-z0-9._-]`: at most 214 characters, cut without
 * leaving a separator dangling, and never one of the two names npm refuses -
 * `fallback` then. A folder named after a long ticket title produced a
 * package.json `npm install` rejected with "name can no longer contain more
 * than 214 characters" before it had installed anything.
 */
export function withinNpmNameRules(name: string, fallback = "abap2ui5-app"): string {
  const capped =
    name.length > NPM_NAME_MAX ? name.slice(0, NPM_NAME_MAX).replace(/[._-]+$/, "") : name;
  return capped && !NPM_BLOCKED_NAMES.has(capped) ? capped : fallback;
}

/** npm package names: lower case, no spaces, no leading dot or underscore,
 *  and npm's length and reserved-name rules (`withinNpmNameRules`). */
export function projectNameFrom(folderName: string): string {
  const name = folderName
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^[._-]+/, "")
    .replace(/-+$/, "");
  return withinNpmNameRules(name);
}

/*
 * The files that turn a class into a PROJECT - what "New Project from
 * Template" writes.
 *
 * Why this exists: "New App from Template" hands out one class, at the cursor
 * or as an untitled document. That is the right thing when you already have a
 * repository. When you do not, it leaves the user with the one artefact the
 * extension cannot check properly: no `abap2ui5lint.jsonc` means the view
 * check falls back to VS Code settings, and the first CI run in that
 * repository disagrees with what the editor had been saying. The config the
 * extension itself searches for is the thing a new project was missing.
 *
 * WHERE THE CONTENT COMES FROM. abap2UI5/app-template is the ecosystem's
 * starting point, and a new project is that repository's files:
 * `src/data/app-template.json` is a snapshot of them, regenerated by
 * `npm run app-template`, shipped next to the bundle as
 * `dist/app-template.json` and read on demand (see `setAppTemplate`), and
 * refreshed weekly by `.github/workflows/bump-app-template.yml`. Copied, not
 * re-typed, because re-typed is what this file used to do and the copy had
 * drifted: it emitted `@abap2ui5/linter@^0.1.1` while the ecosystem was on
 * 0.2.1, no framework pin at all (a scaffolded project therefore resolved
 * abap2UI5's moving default branch - the exact failure app-template's config
 * comment documents), no `chain-house-layout` rule, and no AGENTS.md, so an
 * agent starting a project from inside the IDE got no briefing at all.
 *
 * Generated rather than cloned, still, and deliberately: `abap2ui5.newProject`
 * is registered by the WEB entry too (`src/web/extension.ts`, no `when`
 * clause hiding it), and in vscode.dev there is no git, no child process and
 * no guarantee of network. An offline, deterministic scaffold is also
 * testable, which the rest of this extension is built to be.
 *
 * WHICH files, and what is changed in them, is the template's answer too:
 * its `template.json` (snapshotted with the files) lists what a project
 * takes - `files.shared` and `files.named` - and, under `substitutions`,
 * which text in which file carries a name: the placeholder class in the
 * listed files and paths in the listed cases (the starter class, its sidecar
 * and test include, and the documentation that names it - AGENTS.md,
 * `docs/project.md`), one XML element for the package text, one XML element
 * and one JSON key for the repository name. That description is what the
 * template's own `scripts/rename.mjs`, its `create-abap2ui5-app` package and
 * mcp-server's `scaffold_app` execute, and `scaffoldFiles` below executes
 * nothing else: every listed file, each substitution on the file that names
 * it. So a project created here IS the project created there, and a file or
 * a substitution the template adds reaches a new project without an edit
 * here.
 *
 * It was not always so. The scaffold used to COMPOSE three of the shared
 * files itself - `package.json` (minus the scripts that ran files out of a
 * `scripts/` directory a project did not get), the CI workflow (minus the
 * step running one of them) and AGENTS.md (its own head above the framework
 * guide, which the template inlined below a provenance marker). Each of those
 * was a second description next to the template's, and each went stale: the
 * template made its scripts shared files, moved the guide into ONE file
 * under the build-an-app skill
 * (`.claude/skills/build-an-app/references/building-apps.md`) and left
 * AGENTS.md with the project's own part plus a generated block of the
 * guide's essentials between two marker lines - at which point the composed
 * AGENTS.md would have carried no guide at all, and the composed
 * `package.json` lacked the `npm run doctor` and `npm run add-addon` the
 * template's own AGENTS.md tells a reader to run.
 *
 * The starter class is therefore the TEMPLATE's starter class, not one of
 * the gallery's: the test include asserts on that class's own attributes,
 * and the gallery stays with "New App from Template", which adds a class to a
 * repository that already exists.
 *
 * What is still WRITTEN here is the one file the template says a project
 * writes for itself (`files.templateOwn`: "README.md ... describes the
 * template itself; a project writes its own"). It takes the framework pin out
 * of the snapshot rather than repeating it. `src/test/scaffold.test.ts` is
 * the gate over all of it.
 *
 * `vscode`-free on purpose: the content is data, so the test suite runs the
 * generated class through the bundled linter the same way it does the
 * single-class templates.
 */

import { frameworkPinOf } from "./compat";

/**
 * The snapshot's shape - the type of the generated file, not a second
 * description of it (`typeof import( )` is a type query; nothing of the
 * 300 KB file is bundled for it).
 */
export type AppTemplateSnapshot = {
  files: Record<string, string>;
  template: (typeof import("./data/app-template.json"))["template"];
};

/*
 * NOT bundled. The snapshot is 300 KB - 27% of the desktop bundle when it was
 * an imported JSON module, parsed by every window that activates the
 * extension, for a command that most windows never run. `esbuild.js` ships
 * it next to the bundle (`dist/app-template.json`, like `properties.json`),
 * and the two commands that need it read it through `workspace.fs` on both
 * hosts and hand it in here (`apptemplatefile.ts`) before they ask anything
 * below. The test suite hands in the file directly. Asking before it is in
 * is a programming error, and says so.
 */
let loaded: AppTemplateSnapshot | undefined;
let loading: Promise<void> | undefined;

/** Hands the snapshot in - parsed JSON of `app-template.json`. The shape is
 *  checked here so a truncated or foreign file fails this call, not a
 *  `files.shared` read three functions down. */
export function setAppTemplate(snapshot: unknown): void {
  const s = snapshot as Partial<AppTemplateSnapshot> | null;
  if (
    !s ||
    typeof s !== "object" ||
    typeof s.files !== "object" ||
    !s.files ||
    typeof s.template !== "object" ||
    !s.template ||
    !Array.isArray(s.template.files?.shared) ||
    !Array.isArray(s.template.files?.named) ||
    typeof s.template.placeholderClass !== "string" ||
    typeof s.template.substitutions !== "object"
  ) {
    throw new Error("app-template.json is not an app-template snapshot (files + template expected)");
  }
  loaded = s as AppTemplateSnapshot;
}

/** Whether `setAppTemplate` has been called. */
export function appTemplateLoaded(): boolean {
  return loaded !== undefined;
}

/**
 * Loads the snapshot once through `read` (the text of `app-template.json`)
 * - concurrent callers share the one read, and a read that failed is tried
 * again by the next caller rather than remembered.
 */
export function loadAppTemplate(read: () => Promise<string>): Promise<void> {
  if (loaded) {
    return Promise.resolve();
  }
  if (!loading) {
    loading = read()
      .then((text) => setAppTemplate(JSON.parse(text)))
      .finally(() => {
        loading = undefined;
      });
  }
  return loading;
}

function snapshot(): AppTemplateSnapshot {
  if (!loaded) {
    throw new Error(
      "the app-template snapshot is not loaded - loadAppTemplate( ) comes first"
    );
  }
  return loaded;
}

/** app-template's files, exactly as that repository has them. */
export function templateFiles(): Record<string, string> {
  return snapshot().files;
}

/** app-template's own description of what a project takes from it - the file
 *  lists and the substitutions, snapshotted with the files themselves. One
 *  list, in the repository that owns it; `npm run rename` over there and
 *  mcp-server's `scaffold_app` execute the same one. */
export function templateSpec(): AppTemplateSnapshot["template"] {
  return snapshot().template;
}

/** Every file a project takes from the template, in the template's order:
 *  `files.shared`, then `files.named`. */
export function projectFilePaths(): string[] {
  const { shared, named } = templateSpec().files;
  return [...shared, ...named];
}

/** The files a substitution can touch at all - mirrors `substitutedFiles` in
 *  app-template's `scripts/lib/substitute.mjs`. */
export function substitutedFilePaths(): string[] {
  const subs = templateSpec().substitutions;
  return [
    ...new Set<string>([
      ...subs.class.files,
      ...subs.packageText.map((t: { file: string }) => t.file),
      ...subs.repo.map((t: { file: string }) => t.file),
    ]),
  ];
}

/** The template's shared files a project gets byte for byte: the ones no
 *  substitution names. */
export function verbatimFilePaths(): string[] {
  const substituted = new Set(substitutedFilePaths());
  return templateSpec().files.shared.filter((f: string) => !substituted.has(f));
}

/** The template's name-carrying files - the starter class, its sidecar and
 *  test include, the abapGit and package descriptors. */
export function namedFilePaths(): string[] {
  return [...templateSpec().files.named];
}

/** The class the template's named files are written for. */
export function placeholderClass(): string {
  return templateSpec().placeholderClass;
}

// ---------------------------------------------------------------------------
// The substitutions template.json describes - mirrored from app-template's
// scripts/lib/substitute.mjs, one function each, so the three executors make
// the same edits. Pure functions of text: where it comes from and goes is the
// caller's.
// ---------------------------------------------------------------------------

/** The class, in the cases the spec lists: `lower` is how the ABAP writes
 *  it, `upper` how the sidecar's CLSNAME does - and renaming one spelling
 *  without the other produces an object abapGit imports under one name and
 *  ABAP activates under another. Every occurrence. */
export function applyClass(
  text: string,
  oldClass: string,
  newClass: string,
  cases: readonly string[] = ["lower", "upper"]
): string {
  let out = text;
  for (const spelling of cases) {
    const from = spelling === "upper" ? oldClass.toUpperCase() : oldClass.toLowerCase();
    const to = spelling === "upper" ? newClass.toUpperCase() : newClass.toLowerCase();
    out = out.split(from).join(to);
  }
  return out;
}

/** A value as XML element text, escaped the way abapGit serializes it - an
 *  apostrophe included, as `&apos;`, or the descriptor comes back different
 *  on the first pull. */
export function xmlEscape(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

/** One XML element's text - `<CTEXT>abap2UI5 app</CTEXT>` - replaced in
 *  place, first occurrence: the descriptors carry each element once. The
 *  value is escaped, and passed through a function so a `$&` in it stays
 *  literal. */
export function applyElement(text: string, element: string, value: string): string {
  const replacement = `<${element}>${xmlEscape(value)}</${element}>`;
  return text.replace(new RegExp(`<${element}>[^<]*</${element}>`), () => replacement);
}

/** One top-level JSON string key - `"name": "abap2ui5-app"` - replaced as
 *  text, so the file's formatting survives. The value is written as a JSON
 *  string, through a function so a `$&` in it stays literal. */
export function applyJsonKey(text: string, key: string, value: string): string {
  const replacement = `"${key}": ${JSON.stringify(value)}`;
  return text.replace(new RegExp(`"${key}":\\s*"[^"]*"`), () => replacement);
}

/** Why a valid ABAP class name is still not one a NEW PROJECT may take, or
 *  undefined: app-template's own `abaplint.jsonc` names classes
 *  `^ZCL_|^ZCX_`, and template.json states that as `substitutions.class.rule`.
 *  `ycl_app` or `zmy_app` passed the wizard and failed the project's first
 *  `npm run check`. */
export function projectClassNameError(name: string): string | undefined {
  const cls = templateSpec().substitutions.class;
  if (cls.rule && !new RegExp(cls.rule, "i").test(name.trim())) {
    return `The project's abaplint naming rule expects ZCL_ (or ZCX_) followed by letters, digits or _ - "${name.trim()}" would fail its first check.`;
  }
  return undefined;
}

/** The class is in the FILE names too: `src/zcl_app_001.clas.abap` becomes
 *  `src/zcl_my_app.clas.abap` - when the spec says so. */
export function substitutePath(rel: string, newClass: string): string {
  const cls = templateSpec().substitutions.class;
  return cls.renamesPath ? rel.split(placeholderClass()).join(newClass.toLowerCase()) : rel;
}

/**
 * The whole personalisation of one file, as template.json describes it:
 * `rel` is the file's path in the template, the result the content a project
 * gets under `substitutePath(rel)`. A file no substitution names comes back
 * unchanged. `packageText` is the ABAP package description abapGit shows.
 */
export function substituteText(
  rel: string,
  text: string,
  names: { className: string; projectName: string; packageText?: string }
): string {
  const subs = templateSpec().substitutions;
  let out = text;
  if (subs.class.files.includes(rel)) {
    out = applyClass(out, placeholderClass(), names.className.toLowerCase(), subs.class.cases);
  }
  for (const t of subs.packageText) {
    if (t.file === rel) {
      out = applyElement(out, t.element, names.packageText ?? names.projectName);
    }
  }
  for (const t of subs.repo as Array<{ file: string; element?: string; jsonKey?: string }>) {
    if (t.file !== rel) {
      continue;
    }
    out = t.element
      ? applyElement(out, t.element, names.projectName)
      : t.jsonKey
        ? applyJsonKey(out, t.jsonKey, names.projectName)
        : out;
  }
  return out;
}

/**
 * The files a project takes from the template - every one `template.json`
 * lists, under its substituted path, with the substitutions that name it
 * applied. abapGit serializes its XML with a UTF-8 BOM (the template's named
 * `.xml` files carry one, the snapshot holds the text), so the writer puts it
 * back on those.
 */
export function templateProjectFiles(
  projectName: string,
  className: string,
  packageText: string = projectName
): ScaffoldFile[] {
  const named = new Set(namedFilePaths());
  return projectFilePaths().map((rel) => ({
    path: substitutePath(rel, className),
    content: substituteText(rel, templateFiles()[rel], { className, projectName, packageText }),
    ...(named.has(rel) && rel.endsWith(".xml") ? { bom: true } : {}),
  }));
}

/** The starter class as a project gets it - the template's, renamed. */
export function starterClassSource(className: string): string {
  const rel = namedFilePaths().find((f) => /\.clas\.abap$/.test(f));
  return rel ? substituteText(rel, templateFiles()[rel], { className, projectName: "" }) : "";
}

/*
 * The layout of the template's AGENTS.md, as far as this extension names it
 * to a user (the scaffolded README, the agent setup's next steps): the
 * essentials of the framework's app-building guide sit between two marker
 * lines - `ESSENTIALS_BEGIN` / `ESSENTIALS_END` in app-template's
 * `scripts/app-guide-deviations.mjs`; the begin line carries a sentence after
 * this prefix - and the whole guide is ONE file, `TEMPLATE_GUIDE_FILE` there.
 * `scripts/generate-app-template.mjs` refuses a snapshot that lost either.
 */
export const ESSENTIALS_BEGIN = "<!-- guide-essentials:begin";
export const ESSENTIALS_END = "<!-- guide-essentials:end -->";
/** The framework's app-building guide in a project - the one copy. */
export const GUIDE_FILE = ".claude/skills/build-an-app/references/building-apps.md";

/** The generated essentials block of an AGENTS.md, marker lines included -
 *  or the empty string when it has none. */
export function essentialsBlock(agents: string): string {
  const begin = agents.indexOf(ESSENTIALS_BEGIN);
  const end = agents.indexOf(ESSENTIALS_END);
  return begin === -1 || end < begin ? "" : agents.slice(begin, end + ESSENTIALS_END.length);
}

export interface ScaffoldFile {
  /** Path relative to the project root, POSIX separators. */
  path: string;
  content: string;
  /** abapGit serializes its XML with a UTF-8 BOM, and a BOM-less file comes
   *  back changed on the first pull - for everyone. */
  bom?: boolean;
}

/** The framework release app-template pins abaplint's clone to - named in the
 *  scaffolded README so the reader installs the release the lint assumes. */
export function frameworkPin(): string {
  // the one parser of that file - `compat.ts` reads a workspace's pin with it
  return frameworkPinOf(templateFiles()["abaplint.jsonc"]);
}


#!/usr/bin/env node
/*
 * Builds src/data/repo-dirs.json - the directory names a sibling checkout can
 * carry, taken from abap2UI5/mcp-server's lib/repo-dirs.json.
 *
 * Why the MCP server owns the list: it is the component that RESOLVES the
 * repos root, and it has to keep resolving a checkout somebody made under an
 * older repository name. This extension probes the same root (the MCP
 * registration in src/mcp.ts, the local view-check fallback in
 * src/viewcheck.ts, the example catalogues in src/exampleview.ts), and used to
 * carry a hand-written second copy in src/repolayout.ts - two lists, no gate,
 * so the next rename would have landed in one of them and half-worked.
 *
 * Why a snapshot and not an import: mcp-server is not a dependency of this
 * extension - it is a program the extension may START, from a checkout or via
 * npx, and it is not there at all in the web build. So the content ships
 * inside the bundle, the same way app-template.json and client-api.json do,
 * and the same weekly gate keeps it honest.
 *
 *   node scripts/generate-repo-dirs.mjs /path/to/mcp-server
 *   node scripts/generate-repo-dirs.mjs           (fetches from GitHub main)
 *   node scripts/generate-repo-dirs.mjs --check   (fail when the committed
 *                                                  JSON is stale - what the
 *                                                  weekly workflow runs)
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
// under src/ so tsc (rootDir: src, resolveJsonModule) can import it; esbuild
// inlines it into both bundles, so the web build needs no fs for it either
const OUT = path.join(ROOT, "src", "data", "repo-dirs.json");
const REPO = "abap2UI5/mcp-server";
const SOURCE_FILE = "lib/repo-dirs.json";
const RAW = `https://raw.githubusercontent.com/${REPO}/main/${SOURCE_FILE}`;

/** The keys src/repolayout.ts turns into exported constants. A key that
 *  disappears upstream must fail here, not resolve to `undefined` in an
 *  editor session. */
export const REQUIRED_KEYS = ["corpus", "samples", "samplesStack", "viewCheck", "server"];

async function read(local) {
  if (local) {
    return fs.readFileSync(path.join(local, SOURCE_FILE), "utf8");
  }
  const res = await fetch(RAW);
  if (!res.ok) {
    console.error(`generate-repo-dirs: ${RAW} -> HTTP ${res.status}`);
    process.exit(2);
  }
  return res.text();
}

const invokedDirectly =
  process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const local = args.find((a) => !a.startsWith("--"));

  const source = JSON.parse((await read(local)).replace(/\r\n/g, "\n"));
  const repos = source.repos || {};

  const missing = REQUIRED_KEYS.filter(
    (k) => !Array.isArray(repos[k]?.dirs) || repos[k].dirs.length === 0
  );
  if (missing.length) {
    console.error(
      `generate-repo-dirs: ${SOURCE_FILE} no longer carries a non-empty dirs[] for: ${missing.join(", ")}`
    );
    console.error("Fix src/repolayout.ts (and this script) rather than committing a snapshot it cannot read.");
    process.exit(1);
  }

  // Only what this extension consumes: the directory names. The env vars and
  // probe files are the server's business - it is the one that resolves.
  const dirs = Object.fromEntries(REQUIRED_KEYS.map((k) => [k, repos[k].dirs]));

  const json = `${JSON.stringify(
    {
      note: `Directory names each sibling checkout can carry, newest first. Snapshot of ${REPO}'s ${SOURCE_FILE}, which is the source of truth for the ecosystem's rename history. Generated by scripts/generate-repo-dirs.mjs - do not edit.`,
      source: REPO,
      dirs,
    },
    null,
    2
  )}\n`;

  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== json) {
      console.error(
        "repo-dirs.json is STALE against abap2UI5/ai-mcp - a checkout the MCP server finds is one this extension would not. Run `npm run repo-dirs` and commit."
      );
      process.exit(1);
    }
    console.log(`repo-dirs.json: up to date (${REQUIRED_KEYS.length} repos)`);
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, json);
    console.log(
      `repo-dirs.json: ${REQUIRED_KEYS.length} repos from ${local ? local : `${REPO}@main`}`
    );
  }
}
